#!/usr/bin/env bash
# ============================================================
# BigData / Docker 管理器 —— 局域网一键启动（账号登录模式）
#
# 用法：
#   ./start-lan.sh                  局域网可访问，不设令牌（推荐，学生用账号登录）
#   ./start-lan.sh mytoken         可选：设置令牌（带令牌的请求视为管理员）
#   ./start-lan.sh mytoken 9000    可选：自定义端口
#
# 注意：不要把令牌发给学生！带正确令牌的请求会被视为管理员。
# ============================================================

cd "$(dirname "$0")" || { echo "[错误] 无法进入脚本目录"; exit 1; }

# === 默认令牌（留空 = 使用账号登录；不要发给学生）===
TOKEN=""
PORT=8000

# 命令行覆盖
[ -n "$1" ] && TOKEN="$1"
[ -n "$2" ] && PORT="$2"

echo "启动局域网模式：令牌=${TOKEN} 端口=${PORT}"
exec ./start.sh lan "$TOKEN" "$PORT"
